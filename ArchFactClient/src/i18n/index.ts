function getInitialLocale(): AppLocale {
  try {
    const saved = globalThis.localStorage?.getItem(STORAGE_KEY)
    if (saved === 'zh-CN' || saved === 'en-US') return saved
  } catch {
    // Storage may be unavailable in privacy-restricted environments.
  }
  return globalThis.navigator?.language?.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US'
}

const localeState = ref<AppLocale>(getInitialLocale())

export function translate(key: string, params: MessageParams = {}) {
  const messages = localeState.value === 'zh-CN' ? zh : en
  const template = messages[key] ?? en[key] ?? key
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`))
}

export function localizeKnownText(value: string) {
  if (localeState.value !== 'zh-CN') return value
  return knownChineseText[value] ?? value
}

export function setLocale(locale: AppLocale) {
  localeState.value = locale
}

export function toggleLocale() {
  setLocale(localeState.value === 'zh-CN' ? 'en-US' : 'zh-CN')
}

watch(
  localeState,
  (locale) => {
    try {
      globalThis.localStorage?.setItem(STORAGE_KEY, locale)
    } catch {
      // The language still changes for the current session when storage is blocked.
    }
    if (typeof globalThis.document !== 'undefined') {
      globalThis.document.documentElement.lang = locale
    }
  },
  { immediate: true },
)

export function useI18n() {
  return {
    locale: readonly(localeState),
    isChinese: computed(() => localeState.value === 'zh-CN'),
    t: translate,
    localize: localizeKnownText,
    setLocale,
    toggleLocale,
  }
}
